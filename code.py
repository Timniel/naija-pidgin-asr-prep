import re

# --- Step 1: Define the function (the "recipe") ---
def parse_conllu_for_asr(filepath):
    """
    Parses a CoNLL-U file to extract information needed for ASR.
    **UPDATED to use 'text_ortho' for clean, punctuated transcriptions.**
    """
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    sentences = content.strip().split('\n\n')

    asr_data = []

    for sentence_block in sentences:
        lines = sentence_block.strip().split('\n')

        metadata = {}
        token_lines = []
        for line in lines:
            if line.startswith('#'):
                match = re.match(r'#\s*([^=]+?)\s*=\s*(.*)', line)
                if match:
                    key, value = match.groups()
                    metadata[key.strip()] = value.strip()
            elif line and not line.startswith('#'):
                token_lines.append(line)

        if 'sound_url' in metadata and 'text_ortho' in metadata and token_lines:
            try:
                first_word_misc = token_lines[0].split('\t')[-1]
                start_time = int(re.search(r'AlignBegin=(\d+)', first_word_misc).group(1))

                last_word_misc = token_lines[-1].split('\t')[-1]
                end_time = int(re.search(r'AlignEnd=(\d+)', last_word_misc).group(1))

                transcription = metadata['text_ortho'].strip()

                asr_data.append({
                    "sent_id": metadata.get('sent_id'),
                    "sound_url": metadata.get('sound_url'),
                    "start_ms": start_time,
                    "end_ms": end_time,
                    "transcription": transcription
                })
            except (AttributeError, IndexError):
                # This part is optional, but good for debugging
                # print(f"Skipping block for sent_id: {metadata.get('sent_id')} (missing timing info)")
                continue

    return asr_data

