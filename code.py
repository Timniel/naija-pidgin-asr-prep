print("--- STAGE 2: Converting all MP3s to WAV format ---")

# Get a list of all downloaded MP3s
mp3_files = [os.path.join("full_mp3s", f) for f in os.listdir("full_mp3s") if f.endswith(".mp3")]
print(f"Found {len(mp3_files)} MP3s to convert.")

def convert_mp3_to_wav(mp3_path):
    """Converts a single MP3 to WAV if the WAV doesn't already exist."""
    try:
        base_filename = os.path.basename(mp3_path)
        filename_no_ext = os.path.splitext(base_filename)[0]
        wav_path = os.path.join("full_wavs", f"{filename_no_ext}.wav")

        if not os.path.exists(wav_path):
            command = ["ffmpeg", "-i", mp3_path, "-y", wav_path, "-loglevel", "error"]
            subprocess.run(command, check=True)
        return f"Converted: {base_filename}"
    except Exception as e:
        return f"Failed to convert: {os.path.basename(mp3_path)} - {e}"

# Run conversions in parallel
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor: # Use fewer workers for CPU-bound tasks
    list(tqdm(executor.map(convert_mp3_to_wav, mp3_files), total=len(mp3_files)))

print("\n--- Conversion stage complete. ---\n")


# ==============================================================================
# STAGE 3: SLICE ALL CLIPS FROM THE WAV FILES
# ==============================================================================
print("--- STAGE 3: Slicing clips from WAV files ---")

def slice_clip(item_with_index):
    """Slices a single clip from its corresponding WAV file."""
    index, item = item_with_index
    try:
        base_filename = os.path.basename(item['sound_url'])
        filename_no_ext = os.path.splitext(base_filename)[0]
        wav_path = os.path.join("full_wavs", f"{filename_no_ext}.wav")

        audio = AudioSegment.from_wav(wav_path)
        clip = audio[item['start_ms']:item['end_ms']]

        clip_filename = f"pidgin_{index + 1:04d}.wav"
        clip_path = os.path.join("clips", clip_filename)
        clip.export(clip_path, format="wav")
        return (clip_path, item)
    except Exception:
        return None

# Run slicing in parallel
results = []
tasks = list(enumerate(filtered_data))
with concurrent.futures.ThreadPoolExecutor(max_workers=16) as executor:
    future_to_item = {executor.submit(slice_clip, task): task for task in tasks}
    for future in tqdm(concurrent.futures.as_completed(future_to_item), total=len(tasks)):
        result = future.result()
        if result is not None:
            results.append(result)

# --- Final update and count ---
successful_count = 0
for clip_path, original_item in results:
    original_item['audio_filepath'] = clip_path
    successful_count += 1

print(f"\n--- Slicing complete! Successfully generated {successful_count} clips. ---")

