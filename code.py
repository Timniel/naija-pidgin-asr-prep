unique_urls = sorted(list(set(item['sound_url'] for item in filtered_data)))
print(f"Found {len(unique_urls)} unique MP3 files to download.")

def download_url(url):
    """Downloads a single URL if it doesn't already exist."""
    try:
        base_filename = os.path.basename(url)
        local_mp3_path = os.path.join("full_mp3s", base_filename)
        if not os.path.exists(local_mp3_path):
            response = requests.get(url, timeout=30)
            response.raise_for_status()
            with open(local_mp3_path, 'wb') as f:
                f.write(response.content)
            return f"Downloaded: {base_filename}"
        return f"Skipped (already exists): {base_filename}"
    except Exception as e:
        return f"Failed: {os.path.basename(url)} - {e}"

# Run downloads in parallel
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
    list(tqdm(executor.map(download_url, unique_urls), total=len(unique_urls)))

print("\n--- Download stage complete. ---\n")


